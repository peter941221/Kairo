#!/usr/bin/env python3
"""Render Phase 1 serving evidence into a Markdown table and dependency-free SVG."""
from __future__ import annotations
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "evidence/phase1/serving-benchmark-repeats.jsonl"
OUT_MD = ROOT / "docs/generated/phase1-serving-results.md"
OUT_SVG = ROOT / "docs/generated/phase1-serving-results.svg"

def median(xs: list[float]) -> float:
    xs = sorted(xs); n = len(xs)
    return (xs[(n - 1) // 2] + xs[n // 2]) / 2

def shown(value: float) -> str:
    """Render decimal benchmark values with conventional half-up intent."""
    return f"{value + 1e-9:.2f}"

def main() -> None:
    rows = [json.loads(line) for line in SOURCE.read_text(encoding="utf-8").splitlines() if line]
    groups: dict[tuple[str, str], list[float]] = defaultdict(list)
    for row in rows: groups[(row["result_id"], row["mode"])].append(row["throughput_tok_s"])
    labels = {"qwen38-c32-p512-c1k": "27B c32 / 1K", "qwen38-c8-p2048-c4k": "27B c8 / 4K"}
    summary = []
    for result_id, label in labels.items():
        graph, eager = median(groups[(result_id, "FULL_DECODE_ONLY")]), median(groups[(result_id, "eager")])
        summary.append((label, graph, eager, graph / eager))
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    table = ["# Generated Phase 1 serving results", "", "Generated by `scripts/render_phase1_results.py` from `evidence/phase1/serving-benchmark-repeats.jsonl`.", "", "| Workload | Graph median | Eager median | Ratio |", "|---|---:|---:|---:|"]
    table += [f"| {label} | {shown(g)} tok/s | {shown(e)} tok/s | {shown(ratio)}x |" for label, g, e, ratio in summary]
    OUT_MD.write_text("\n".join(table) + "\n", encoding="utf-8")
    width, height, scale = 760, 250, 1.5
    bars, y = [], 70
    for label, graph, eager, ratio in summary:
        bars += [f'<text x="20" y="{y}">{label}</text>', f'<rect x="180" y="{y-18}" width="{graph/scale:.1f}" height="16" fill="#2563eb"/><text x="{185+graph/scale:.1f}" y="{y-5}">Graph {shown(graph)}</text>', f'<rect x="180" y="{y+6}" width="{eager/scale:.1f}" height="16" fill="#94a3b8"/><text x="{185+eager/scale:.1f}" y="{y+19}">Eager {shown(eager)} ({shown(ratio)}x)</text>']; y += 90
    OUT_SVG.write_text(f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}"><style>text{{font:14px sans-serif;fill:#111827}}</style><text x="20" y="30" style="font-weight:bold">Kairo Phase 1: measured serving throughput (tok/s)</text>{"".join(bars)}</svg>\n', encoding="utf-8")

if __name__ == "__main__": main()
